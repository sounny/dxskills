@dataclass
class EvenLatticeSpec:
    """Specification of an even lattice of signature (2, n)."""
    name: str = "Lattice II_{2,2}"
    signature_pos: int = 2
    signature_neg: int = 2
    dimension: int = 4
    modular_weight_input: float = 0.0  # 1 - n/2 = 1 - 2/2 = 0.0
    level_n: int = 1


@dataclass
class WeaklyHolomorphicForm:
    """Weakly holomorphic modular form f with principal part poles."""
    label: str = "j_invariant_shifted"
    weight: float = 0.0
    constant_term_c0: float = 24.0  # weight of product = c0 / 2 = 12
    # Fourier coefficients c(m) for m in [-1, 0, 1, 2, 3, 4]
    fourier_coeffs: Dict[int, float] = field(default_factory=lambda: {
        -1: 1.0, 0: 24.0, 1: -2048.0, 2: 98304.0, 3: -1843200.0
    })

    def principal_part(self) -> Dict[int, float]:
        """Return negative index terms causing divisor poles/zeroes."""
        return {m: val for m, val in self.fourier_coeffs.items() if m < 0}


@dataclass
class DivisorComponent:
    r"""Component of the divisor of the Borcherds product \Psi(z, f)."""
    norm_q_lambda: float
    multiplicity: float
    order_zero_or_pole: str  # "Zero" or "Pole"
    heegner_divisor_label: str


@dataclass
class BorcherdsProductSpec:
    r"""Automorphic form \Psi(z, f) generated by Borcherds lift."""
    automorphic_weight: float
    weyl_vector_norm: float
    infinite_product_factors_count: int
    divisors: List[DivisorComponent]
    singular_theta_integral_finite: bool = True
    borcherds_modularity_proven: bool = True


